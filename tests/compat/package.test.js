// Consumer-side compatibility of the packed package: JavaScript (ESM, CommonJS) and
// TypeScript (node16 module / commonjs, bundler, node10). Needs `dist/` — built by `pretest`.
// Also checks that the generated src/version.ts matches package.json.
import { test, before, after } from 'node:test'
import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { mkdtempSync, mkdirSync, writeFileSync, copyFileSync, readFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const fixtures = join(root, 'tests', 'compat', 'fixtures')
const tsc = join(root, 'node_modules', 'typescript', 'bin', 'tsc')
const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm'

/** Runs a command and returns its stdout, throws with the full output on failure */
function run(cmd, args, cwd) {
  const r = spawnSync(cmd, args, { cwd, encoding: 'utf8', shell: process.platform === 'win32' })
  if (r.error) {
    throw new Error(`cannot run ${cmd} (${r.error.message}): the compatibility tests need npm on the PATH`)
  }
  if (r.status !== 0) {
    throw new Error(`${cmd} ${args.join(' ')} failed (status ${r.status})\n${r.stdout}\n${r.stderr}`)
  }
  return r.stdout
}

/** Runs a script with node and parses the JSON object it prints on its last line */
function runNode(script, cwd) {
  const lines = run(process.execPath, [script], cwd).trim().split('\n')
  return JSON.parse(lines[lines.length - 1])
}

// ─── Throwaway consumer project: `npm pack` → `npm install <tgz>` ─────────────

let consumer

before(() => {
  consumer = mkdtempSync(join(tmpdir(), 'bitgen-sdk-compat-'))
  // --no-dry-run: when the suite runs from `npm publish --dry-run` (prepublishOnly), npm exports its dry-run
  // flag to nested npm commands, which would then write nothing
  const packed = JSON.parse(run(npm, ['pack', '--json', '--no-dry-run', '--pack-destination', consumer], root))
  // npm <= 11 prints an array, npm 12 an object keyed by package name
  const { filename } = Array.isArray(packed) ? packed[0] : Object.values(packed)[0]
  writeFileSync(join(consumer, 'package.json'), JSON.stringify({ name: 'consumer', private: true }))
  // Local tarball, no dependency: works offline
  run(npm, ['install', '--no-dry-run', '--offline', '--no-audit', '--no-fund', '--no-package-lock', '--ignore-scripts', join(consumer, filename)], consumer)
})

after(() => {
  if (consumer) {
    rmSync(consumer, { recursive: true, force: true })
  }
})

// ─── Version ──────────────────────────────────────────────────────────────────

test('src/version.ts (generated by scripts/prebuild.js) matches package.json', () => {
  const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
  assert.equal(readFileSync(join(root, 'src', 'version.ts'), 'utf8'), `// Generated by scripts/prebuild.js from package.json — do not edit\nexport const VERSION = ${JSON.stringify(version)}\n`)
})

