  writeFileSync(join(consumer, 'cjs.cjs'), `const { BitgenClient, BitgenError, Env, Asset, CoreType, TradingDirection, Locale, WebhookEventName, OrderState, AssetState } = require('@bitgen/sdk')\n${JS_BODY}`)
